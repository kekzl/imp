// Attention cross-path agreement — TEST_AUDIT (retired) risk #1.
//
// The engine has SIX prefill-attention implementations that MUST agree:
// cuBLAS materialized, WMMA FMHA (fmha_sm120), fp8 FMHA, FA2 (e4m3 QK),
// FA2 (f16 QK), and flash_attention_blackwell. The #493 regression shipped
// because nothing asserted cross-path agreement under realistic data — every
// per-kernel parity test was green on benign fills.
//
// Ground truth: an fp64 CPU reference computed from the f16-rounded inputs.
// The reference itself is verified against a committed numpy fp64 golden
// (tests/refs/attention_crosspath_golden.h, 64 spot values per config,
// 1e-9 rel) — proving the in-test reference and the independent generator
// compute the same math. Inputs are heavy-tailed realistic magnitudes
// (cubed-uniform, amp 8, 1/256 outliers to ~±64 — QK-normed model regime),
// generated by an integer LCG with f32 multiply-only transforms so numpy
// and C++ produce bit-identical f16 bits (no libm divergence).
//
// Tolerances (tests/refs/README.md):
//   f16-class (cuBLAS, WMMA, FA2-f16, blackwell): 1e-2 rel vs fp64 ref
//   fp8-class (fp8 FMHA, FA2-e4m3): 5e-2 rel vs fp64 ref (e4m3 score noise)
//   pairwise f16-class agreement: 1e-2 (the killer assert)

