#!/usr/bin/env python3
"""Generate Kimi-Linear chat-template goldens for tests/test_kimi_chat_template.cpp.

Independent reference: the checkpoint's chat_template.jinja (moonshotai/Kimi-Linear-48B-A3B-Instruct,
MIT, copied to tests/fixtures/kimi_linear_chat_template.jinja) rendered by HF transformers'
render_jinja_template, the function apply_chat_template calls, NOT by imp. Writes
tests/refs/kimi_template_golden.h with the template embedded and one expected prompt per case.

Regenerate (CPU container):
  docker run --rm -v $PWD:/work -w /work python:3.12-slim sh -c \
    "pip install -q transformers==4.57.1 jinja2==3.1.6 && python3 -I tests/refs/gen_kimi_template_golden.py"
"""

import transformers
from transformers.utils.chat_template_utils import render_jinja_template

SRC = "tests/fixtures/kimi_linear_chat_template.jinja"
OUT = "tests/refs/kimi_template_golden.h"

TOOL_CALL = {"id": "functions.get_weather:0", "type": "function",
             "function": {"name": "get_weather", "arguments": {"city": "Paris"}}}

CASES = [
    # name, messages
    ("kOneTurn", [{"role": "user", "content": "Hello"}]),
    ("kMultiTurnSystem", [
        {"role": "system", "content": "You are a helpful assistant."},
        {"role": "user", "content": "Hi"},
        {"role": "assistant", "content": "Hello! How can I help?"},
        {"role": "user", "content": "What is 2+2?"},
    ]),
    ("kToolHistory", [
        {"role": "user", "content": "Weather in Paris?"},
        {"role": "assistant", "content": "", "tool_calls": [TOOL_CALL]},
        {"role": "tool", "tool_call_id": "functions.get_weather:0", "content": "18 C, sunny"},
    ]),
]


def render(src, messages):
    out, _ = render_jinja_template(conversations=[messages], chat_template=src, add_generation_prompt=True,
                                   bos_token="[BOS]", eos_token="[EOS]")
    return out[0]


def raw(s):
    assert ")IMPJINJA\"" not in s
    return 'R"IMPJINJA(' + s + ')IMPJINJA"'


def main():
    with open(SRC) as fh:
        src = fh.read()
    with open(OUT, "w") as fh:
        fh.write("// GENERATED by tests/refs/gen_kimi_template_golden.py - do not edit.\n")
        fh.write(f"// transformers {transformers.__version__} render_jinja_template, template {SRC}.\n")
        fh.write("#pragma once\n#include <string>\n\n// clang-format off\nnamespace imp::kimi_golden {\n\n")
        fh.write(f"inline const std::string k_chat_template_jinja = {raw(src)};\n\n")
        for name, messages in CASES:
            fh.write(f"inline const std::string {name} = {raw(render(src, messages))};\n\n")
        fh.write("}  // namespace imp::kimi_golden\n// clang-format on\n")
    print(f"wrote {OUT}: {len(CASES)} cases")


if __name__ == "__main__":
    main()
