#!/usr/bin/env python3
"""Generate Ling-3.0 chat-template goldens for tests/test_ling3_chat_template.cpp.

Independent reference: the checkpoint's chat_template.jinja (inclusionAI/Ling-3.0-tiny, MIT,
copied to tests/fixtures/ling3_chat_template.jinja) rendered by jinja2 the way HF
apply_chat_template does (ImmutableSandboxedEnvironment, trim_blocks, lstrip_blocks,
loopcontrols, tools=None), NOT by imp. Writes tests/refs/ling3_template_golden.h with the
template embedded and one expected prompt per case.

Regenerate (CPU container):
  docker run --rm -v $PWD:/work -w /work python:3.12-slim sh -c \
    "pip install -q jinja2==3.1.4 && python3 tests/refs/gen_ling3_template_golden.py"
"""

import json

import jinja2
import jinja2.ext
from jinja2.sandbox import ImmutableSandboxedEnvironment

SRC = "tests/fixtures/ling3_chat_template.jinja"
OUT = "tests/refs/ling3_template_golden.h"

CASES = [
    # name, messages, extra context
    ("kOneTurnDefault", [{"role": "user", "content": "Hello"}], {}),
    ("kMultiTurnNoThink", [
        {"role": "system", "content": "You are a helpful assistant."},
        {"role": "user", "content": "Hi"},
        {"role": "assistant", "content": "Hello! How can I help?"},
        {"role": "user", "content": "What is 2+2?"},
    ], {"enable_thinking": False}),
    ("kOneTurnThink", [{"role": "user", "content": "Hi"}], {"enable_thinking": True}),
]


def render(src, messages, extra):
    env = ImmutableSandboxedEnvironment(trim_blocks=True, lstrip_blocks=True,
                                        extensions=[jinja2.ext.loopcontrols])
    env.filters["tojson"] = lambda x, ensure_ascii=False, **kw: json.dumps(x, ensure_ascii=ensure_ascii)
    return env.from_string(src).render(messages=messages, tools=None, add_generation_prompt=True,
                                       bos_token="", eos_token="<|role_end|>", **extra)


def raw(s):
    assert ")IMPJINJA\"" not in s
    return 'R"IMPJINJA(' + s + ')IMPJINJA"'


def main():
    with open(SRC) as fh:
        src = fh.read()
    with open(OUT, "w") as fh:
        fh.write("// GENERATED by tests/refs/gen_ling3_template_golden.py - do not edit.\n")
        fh.write(f"// jinja2 {jinja2.__version__}, template {SRC}.\n")
        fh.write("#pragma once\n#include <string>\n\n// clang-format off\nnamespace imp::ling3_golden {\n\n")
        fh.write(f"inline const std::string k_chat_template_jinja = {raw(src)};\n\n")
        for name, messages, extra in CASES:
            fh.write(f"inline const std::string {name} = {raw(render(src, messages, extra))};\n\n")
        fh.write("}  // namespace imp::ling3_golden\n// clang-format on\n")
    print(f"wrote {OUT}: {len(CASES)} cases")


if __name__ == "__main__":
    main()
