#!/usr/bin/env python3
"""Generate group-limited top-k routing goldens for tests/test_moe_group_limit.cpp.

Independent reference: BailingMoeV3Gate.forward / group_limited_topk from
inclusionAI/Ling-3.0-tiny modeling_bailing_moe_v3.py (copied verbatim below), NOT imp.
Ling-3.0-tiny router: 128 experts, top-8, n_group 8, topk_group 4, sigmoid scores,
expert_bias for selection only, weights normalised then * routed_scaling_factor 2.5.

Inputs from the same 31-bit LCG as gen_kda_golden.py (tests/kda_reference.h kda_ref::Lcg).

Regenerate (CPU container):
  docker run --rm -v $PWD:/work -w /work python:3.12-slim sh -c \
    "pip install -q torch==2.5.1 --index-url https://download.pytorch.org/whl/cpu \
     && python3 tests/refs/gen_moe_group_topk_golden.py"
"""

import torch

OUT = "tests/refs/moe_group_topk_golden.h"
N_TOKENS, N_EXPERTS, TOP_K, N_GROUP, TOPK_GROUP, SCALE = 6, 128, 8, 8, 4, 2.5
SEED = 4711


class Lcg:
    def __init__(self, seed):
        self.s = seed % (1 << 31)

    def next(self):
        self.s = (self.s * 1103515245 + 12345) % (1 << 31)
        return float(self.s) / float(1 << 30) - 1.0

    def fill(self, n, amp):
        return torch.tensor([self.next() * amp for _ in range(n)], dtype=torch.float32)


# ---- modeling_bailing_moe_v3.py BailingMoeV3Gate (verbatim logic, module state inlined) ----
def group_limited_topk(scores, n_group, topk_group, num_experts, top_k):
    num_tokens, _ = scores.size()
    group_scores = scores.view(num_tokens, n_group, -1).topk(2, dim=-1)[0].sum(dim=-1)
    group_idx = torch.topk(group_scores, k=topk_group, dim=-1, sorted=False)[1]
    group_mask = torch.zeros_like(group_scores)
    group_mask.scatter_(1, group_idx, 1)
    score_mask = (
        group_mask.unsqueeze(-1)
        .expand(num_tokens, n_group, num_experts // n_group)
        .reshape(num_tokens, -1)
    )
    masked_scores = scores.masked_fill(~score_mask.bool(), float('-inf'))
    probs, top_indices = torch.topk(masked_scores, k=top_k, dim=-1)
    return probs, top_indices


def gate_forward(logits, expert_bias):
    scores = torch.sigmoid(logits.float()).type_as(logits)
    scores_for_routing = scores + expert_bias
    _, topk_idx = group_limited_topk(scores_for_routing, N_GROUP, TOPK_GROUP, N_EXPERTS, TOP_K)
    scores = torch.gather(scores, dim=1, index=topk_idx).type_as(logits)
    topk_weight = scores / (scores.sum(dim=-1, keepdim=True) + 1e-20)
    return topk_idx, topk_weight * SCALE


def main():
    rng = Lcg(SEED)
    logits = rng.fill(N_TOKENS * N_EXPERTS, 4.0).view(N_TOKENS, N_EXPERTS)
    bias = rng.fill(N_EXPERTS, 0.2)
    idx, w = gate_forward(logits, bias)
    # Grouping must matter for the test to mean anything.
    flat_idx = torch.topk(torch.sigmoid(logits) + bias, k=TOP_K, dim=-1)[1]
    differs = sum(set(a.tolist()) != set(b.tolist()) for a, b in zip(idx, flat_idx))
    assert differs >= 2, differs
    order = idx.sort(dim=-1)
    idx_sorted = order.values
    w_sorted = torch.gather(w, 1, order.indices)
    with open(OUT, "w") as fh:
        fh.write("// GENERATED by tests/refs/gen_moe_group_topk_golden.py - do not edit.\n")
        fh.write(f"// torch {torch.__version__}, Ling-3.0 BailingMoeV3Gate, LCG seed {SEED}.\n")
        fh.write("#pragma once\n\n// clang-format off\nnamespace imp::moe_group_topk_golden {\n\n")
        fh.write(f"inline constexpr int kTokens = {N_TOKENS}, kExperts = {N_EXPERTS}, kTopK = {TOP_K};\n")
        fh.write(f"inline constexpr int kNGroup = {N_GROUP}, kTopkGroup = {TOPK_GROUP};\n")
        fh.write(f"inline constexpr float kScale = {SCALE}f;\n")
        fh.write(f"inline constexpr unsigned kSeed = {SEED}u;\n")
        fh.write(f"inline constexpr int kTokensWhereGroupingMatters = {differs};\n\n")
        fh.write("// Selected experts per token, ascending.\n")
        fh.write(f"inline constexpr int kIdx[{N_TOKENS * TOP_K}] = {{\n")
        for row in idx_sorted.tolist():
            fh.write("    " + ", ".join(str(v) for v in row) + ",\n")
        fh.write("};\n\n// Routing weights in kIdx order (normalised, * kScale).\n")
        fh.write(f"inline constexpr float kWeight[{N_TOKENS * TOP_K}] = {{\n")
        for row in w_sorted.tolist():
            fh.write("    " + ", ".join(f"{v:.9g}f" for v in row) + ",\n")
        fh.write("};\n\n}  // namespace imp::moe_group_topk_golden\n// clang-format on\n")
    print(f"wrote {OUT}: grouping changes the selection on {differs}/{N_TOKENS} tokens")


if __name__ == "__main__":
    main()
