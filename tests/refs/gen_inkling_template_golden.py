#!/usr/bin/env python3
"""Generate Inkling2 chat-template goldens for tests/test_inkling_chat_template.cpp.

Independent reference: the checkpoint's chat_template.jinja (thinkingmachines/Inkling-2-Mini,
Apache-2.0, copied to tests/fixtures/inkling2_chat_template.jinja) rendered by HF transformers'
render_jinja_template, the function apply_chat_template calls, NOT by imp. Writes
tests/refs/inkling_template_golden.h with the template embedded and one expected prompt per case.

Regenerate (CPU container):
  docker run --rm -v $PWD:/work -w /work python:3.12-slim sh -c \
    "pip install -q transformers==4.57.1 jinja2==3.1.6 && python3 -I tests/refs/gen_inkling_template_golden.py"
"""

import transformers
from transformers.utils.chat_template_utils import render_jinja_template

SRC = "tests/fixtures/inkling2_chat_template.jinja"
OUT = "tests/refs/inkling_template_golden.h"

TURN = [{"role": "user", "content": "What is 17*23?"}]

# name, messages, reasoning_effort (None = the template's default)
CASES = [
    ("kDefault", TURN, None),
    ("kNone", TURN, "none"),
    ("kMinimal", TURN, "minimal"),
    ("kLow", TURN, "low"),
    ("kMedium", TURN, "medium"),
    ("kHigh", TURN, "high"),
    ("kXhigh", TURN, "xhigh"),
    ("kMax", TURN, "max"),
    ("kNumberHalf", TURN, 0.5),
    ("kNumberQuarter", TURN, 0.25),
    ("kNumberZero", TURN, 0),
    ("kSystemFirst", [{"role": "system", "content": "Be brief."}] + TURN, "low"),
]


def render(src, messages, effort):
    kw = {} if effort is None else {"reasoning_effort": effort}
    out, _ = render_jinja_template(conversations=[messages], chat_template=src, add_generation_prompt=True, **kw)
    return out[0]


def raw(s):
    assert ")IMPJINJA\"" not in s
    return 'R"IMPJINJA(' + s + ')IMPJINJA"'


def main():
    with open(SRC) as fh:
        src = fh.read()
    with open(OUT, "w") as fh:
        fh.write("// GENERATED by tests/refs/gen_inkling_template_golden.py - do not edit.\n")
        fh.write(f"// transformers {transformers.__version__} render_jinja_template, template {SRC}.\n")
        fh.write("#pragma once\n#include <string>\n\n// clang-format off\nnamespace imp::inkling_golden {\n\n")
        fh.write(f"inline const std::string k_chat_template_jinja = {raw(src)};\n\n")
        for name, messages, effort in CASES:
            fh.write(f"inline const std::string {name} = {raw(render(src, messages, effort))};\n\n")
        fh.write("}  // namespace imp::inkling_golden\n// clang-format on\n")
    print(f"wrote {OUT}: {len(CASES)} cases")


if __name__ == "__main__":
    main()
