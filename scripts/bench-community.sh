#!/usr/bin/env bash
# One-command community benchmark: pulls the imp image, downloads two fixed GGUF models from
# Hugging Face (dense Qwen3-8B Q8_0 8.7 GB, MoE gpt-oss-20b MXFP4 12.1 GB), runs imp-cli --bench
# RUNS times per model (fresh process each), prints a Markdown block ready to paste.
# Usage: scripts/bench-community.sh   Env: IMAGE (ghcr.io/kekzl/imp:latest), MODELS_DIR (~/models),
#        RUNS (3), NO_PULL=1 (keep the local image). Needs only Docker + the NVIDIA Container Toolkit.
set -uo pipefail
IMAGE=${IMAGE:-ghcr.io/kekzl/imp:latest}
MODELS_DIR=${MODELS_DIR:-$HOME/models}
RUNS=${RUNS:-3}
# label <TAB> hf:// source <TAB> GiB of VRAM the run needs (weights + bench context + workspace)
MODELS=$'Qwen3-8B Q8_0 (dense)\thf://Qwen/Qwen3-8B-GGUF:Qwen3-8B-Q8_0.gguf\t11
gpt-oss-20b MXFP4 (MoE)\thf://ggml-org/gpt-oss-20b-GGUF:gpt-oss-20b-MXFP4.gguf\t15'

die() { echo "bench-community: $*" >&2; exit 1; }
command -v docker >/dev/null || die "docker not found"
command -v nvidia-smi >/dev/null || die "nvidia-smi not found (NVIDIA driver)"
mkdir -p "$MODELS_DIR" || die "cannot create $MODELS_DIR"
[ "${NO_PULL:-0}" = 1 ] || docker pull -q "$IMAGE" >/dev/null || die "docker pull $IMAGE failed"

q() { nvidia-smi --query-gpu="$1" --format=csv,noheader,nounits | head -1 | sed 's/^ *//;s/ *$//'; }
gpu=$(q name); cc=$(q compute_cap); vram_mib=$(q memory.total); driver=$(q driver_version)
pcie="gen $(q pcie.link.gen.max) x$(q pcie.link.width.max)"; plimit=$(q power.limit)
[ "$cc" = "12.0" ] || echo "warning: compute capability $cc; imp targets 12.0 (sm_120a) only" >&2
imp_ver=$(docker image inspect --format '{{index .Config.Labels "org.opencontainers.image.version"}}' "$IMAGE")
imp_rev=$(docker image inspect --format '{{index .Config.Labels "org.opencontainers.image.revision"}}' "$IMAGE" | cut -c1-8)
cuda=$(docker image inspect --format '{{range .Config.Env}}{{println .}}{{end}}' "$IMAGE" | sed -n 's/^CUDA_VERSION=//p')
os="$(uname -s) $(uname -r)"; grep -qi microsoft /proc/version 2>/dev/null && os="$os (WSL2)"
cpu=$(sed -n 's/^model name[[:space:]]*: //p' /proc/cpuinfo | head -1)
ram=$(awk '/MemTotal/ {printf "%.0f GiB", $2 / 1048576}' /proc/meminfo)

med() { sort -n | awk '{a[NR]=$1} END {if (NR) printf "%.2f (%.2f-%.2f)", a[int((NR+1)/2)], a[1], a[NR]; else printf "failed"}'; }
rows=""
while IFS=$'\t' read -r label src need_gib; do
    if [ "$vram_mib" -lt $(( need_gib * 1024 )) ]; then
        rows+="| $label | skipped: needs ~${need_gib} GiB VRAM | | |"$'\n'; continue
    fi
    pp=(); tg=(); peak=()
    for r in $(seq 1 "$RUNS"); do
        echo "[$label] run $r/$RUNS$([ "$r" = 1 ] && echo " (downloads the model if missing)")" >&2
        line=$(docker run --rm --gpus all --user "$(id -u):$(id -g)" -v "$MODELS_DIR":/models "$IMAGE" \
            imp-cli --model "$src" --bench --bench-pp 512 --bench-reps 5 --max-tokens 128 --temperature 0 \
            --set speculative.ngram=false --json 2>/dev/null | grep '"mode":"bench"' | tail -1)
        [ -n "$line" ] || { echo "[$label] run $r produced no result" >&2; continue; }
        pp+=("$(sed -n 's/.*"prefill_tps":\([0-9.]*\).*/\1/p' <<< "$line")")
        tg+=("$(sed -n 's/.*"decode_tps":\([0-9.]*\).*/\1/p' <<< "$line")")
        peak+=("$(sed -n 's/.*"peak_vram_mib":\([0-9]*\).*/\1/p' <<< "$line")")
    done
    rows+="| $label | $(printf '%s\n' "${pp[@]}" | med) | $(printf '%s\n' "${tg[@]}" | med) | $(printf '%s\n' "${peak[@]}" | sort -n | tail -1) |"$'\n'
done <<< "$MODELS"

cat <<EOF

### imp community benchmark

| | |
|---|---|
| GPU | $gpu, ${vram_mib} MiB, ${plimit} W limit, PCIe $pcie |
| driver / image CUDA | $driver / $cuda |
| imp | $imp_ver (\`$imp_rev\`), \`$IMAGE\` |
| host | $cpu, $ram, $os |

\`imp-cli --bench --bench-pp 512 --bench-reps 5 --max-tokens 128 --temperature 0 --set speculative.ngram=false\`, $RUNS fresh processes per model, median (min-max):

| model | prompt pp512 tok/s | decode tg128 tok/s | peak VRAM MiB |
|---|---:|---:|---:|
${rows%$'\n'}

Generated by \`scripts/bench-community.sh\` on $(date -u +%Y-%m-%d).
EOF
