#!/usr/bin/env python3
"""Log-and-return gate: a wrapper that cannot write its output throws.

src/compute/CLAUDE.md: a kernel that cannot serve its input fails loud. The shape this gate
counts is the one that broke it twice (DEBT_LEDGER row 8, ROADMAP B-108): a log call at ERROR
or WARN level immediately followed (one comment line may sit between) by a bare `return;`,
in src/exec, src/compute and src/quant, against tools/silent_void_return_allowlist.txt.

The list only shrinks: a file with more exits than its budget fails, a file that is not
listed fails, and an entry for a file with fewer exits fails as stale. A designed fallback
(owner decision B-108) logs through IMP_FALLBACK_WARN (core/fallback_site.h: one WARN per
model load plus imp_fallback_total{site}); it counts here too, and every row names its reason.

Usage:
    python3 tools/check_silent_void_returns.py            # check (CI)
    python3 tools/check_silent_void_returns.py --update   # rewrite the allowlist
    python3 tools/check_silent_void_returns.py --list     # file:line of every exit
    python3 tools/check_silent_void_returns.py --selftest
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
ROOTS = ("src/exec", "src/compute", "src/quant")
ALLOWLIST = REPO / "tools" / "silent_void_return_allowlist.txt"
SUFFIXES = (".cpp", ".cu", ".h", ".cuh", ".hpp")
LOG_CALL = re.compile(r"\bIMP_(?:LOG_(?:ERROR|WARN)|FALLBACK_WARN)\s*\(")
# After the call's `;`: optional single `//` line, then a bare return.
TAIL = re.compile(r"\s*;[ \t]*\n(?:[ \t]*//[^\n]*\n)?[ \t]*return\s*;")


def call_end(text: str, i: int) -> int:
    """Index after the `)` matching the `(` at text[i - 1]; -1 if unbalanced."""
    depth = 1
    n = len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            i += 1
            while i < n and text[i] != c:
                i += 2 if text[i] == "\\" else 1
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return -1


def find_lines(text: str) -> list[int]:
    lines = []
    for m in LOG_CALL.finditer(text):
        line_start = text.rfind("\n", 0, m.start()) + 1
        if text[line_start:m.start()].lstrip().startswith(("//", "*", "/*")):
            continue
        end = call_end(text, m.end())
        if end >= 0 and TAIL.match(text, end):
            lines.append(text.count("\n", 0, m.start()) + 1)
    return lines


def scan() -> dict[str, list[int]]:
    hits: dict[str, list[int]] = {}
    for root in ROOTS:
        for path in sorted((REPO / root).rglob("*")):
            if path.suffix not in SUFFIXES or not path.is_file():
                continue
            lines = find_lines(path.read_text(encoding="utf-8", errors="replace"))
            if lines:
                hits[path.relative_to(REPO).as_posix()] = lines
    return hits


def parse_row(s: str) -> tuple[str, int, str]:
    """`path  # N  reason` -> (path, N, reason); reason is "" when the row has none."""
    path, _, rest = s.partition("#")
    count, _, reason = rest.strip().partition(" ")
    return path.strip(), int(count), reason.strip()


def read_allowlist() -> tuple[dict[str, int], dict[str, str]]:
    counts: dict[str, int] = {}
    reasons: dict[str, str] = {}
    if not ALLOWLIST.exists():
        return counts, reasons
    for line in ALLOWLIST.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        path, count, reason = parse_row(s)
        counts[path] = count
        reasons[path] = reason
    return counts, reasons


def write_allowlist(hits: dict[str, int], reasons: dict[str, str]) -> None:
    body = [
        "# Log-and-return allowlist: files in src/exec, src/compute, src/quant where a log call at ERROR",
        "# or WARN level (or IMP_FALLBACK_WARN) is followed by a bare `return;`.",
        "# Generated by tools/check_silent_void_returns.py --update. THIS LIST ONLY SHRINKS:",
        "# a new exit that leaves an output unwritten throws (imp::throw_runtime_error) or returns a",
        "# status its caller checks; it does not log and return (src/compute/CLAUDE.md, ROADMAP B-108).",
        "# A designed fallback takes IMP_FALLBACK_WARN (one WARN per model load, imp_fallback_total).",
        "# Row: `path  # exits  reason` (what runs instead); a row without a reason fails.",
        "#",
        f"# remaining: {len(hits)} files, {sum(hits.values())} exits",
        "",
    ]
    body += [f"{rel}  # {hits[rel]}  {reasons.get(rel, '')}".rstrip() for rel in sorted(hits)]
    ALLOWLIST.write_text("\n".join(body) + "\n", encoding="utf-8")


def reason_fails(hits: dict[str, int], reasons: dict[str, str]) -> list[str]:
    return [f"FAIL {rel}: allowlist row has no reason (what runs instead, at what cost)"
            for rel in sorted(hits) if rel in reasons and not reasons[rel]]


def verdict(hits: dict[str, int], allowed: dict[str, int]) -> list[str]:
    fails = []
    for rel in sorted(hits):
        if rel not in allowed:
            fails.append(f"FAIL {rel}: {hits[rel]} log-and-return exit(s), file not on the allowlist")
        elif hits[rel] > allowed[rel]:
            fails.append(f"FAIL {rel}: {hits[rel]} exit(s), budget {allowed[rel]}")
    for rel in sorted(allowed):
        if rel not in hits:
            fails.append(f"FAIL {rel}: listed but no exit left; delete the entry (--update)")
        elif hits[rel] < allowed[rel]:
            fails.append(f"FAIL {rel}: {hits[rel]} exit(s), budget {allowed[rel]}: lower it (--update)")
    return fails


def selftest() -> int:
    cases = [
        ("a new file", {"a.cpp": 1}, {}, 1),
        ("over budget", {"a.cpp": 3}, {"a.cpp": 2}, 1),
        ("stale entry", {}, {"a.cpp": 2}, 1),
        ("under budget", {"a.cpp": 1}, {"a.cpp": 2}, 1),
        ("exact", {"a.cpp": 2, "b.cu": 1}, {"a.cpp": 2, "b.cu": 1}, 0),
    ]
    ok = 0
    for name, hits, allowed, want in cases:
        got = len(verdict(hits, allowed))
        if (got > 0) == (want > 0):
            ok += 1
        else:
            print(f"selftest FAIL: {name}: {got} failure(s), wanted {'some' if want else 'none'}")
    rows = [
        ("row with a reason", "src/a.cpp  # 2  dense prefill instead", ("src/a.cpp", 2, "dense prefill instead"), 0),
        ("row without a reason", "src/a.cpp  # 2", ("src/a.cpp", 2, ""), 1),
    ]
    for name, row, want_parse, want_fails in rows:
        path, count, reason = parse_row(row)
        got = len(reason_fails({path: count}, {path: reason}))
        if (path, count, reason) == want_parse and got == want_fails:
            ok += 1
        else:
            print(f"selftest FAIL: {name}: parsed {(path, count, reason)}, {got} reason failure(s)")
    texts = [
        ("error then return", 'if (x) {\n    IMP_LOG_ERROR("a %d", n);\n    return;\n}\n', [2]),
        ("warn, multi-line call, `;` and `)` in the string",
         'IMP_LOG_WARN("a; b) %s",\n             name(x));\n    return;\n', [1]),
        ("one comment line between", 'IMP_LOG_ERROR("a");\n  // why\n  return;\n', [1]),
        ("return with a trailing comment", 'IMP_LOG_WARN("a");\n  return;  // hint only\n', [1]),
        ("two comment lines between", 'IMP_LOG_ERROR("a");\n  // x\n  // y\n  return;\n', []),
        ("status return", 'IMP_LOG_ERROR("a");\n  return false;\n', []),
        ("throw after the log", 'IMP_LOG_ERROR("a");\n  throw std::runtime_error("a");\n', []),
        ("info level", 'IMP_LOG_INFO("a");\n  return;\n', []),
        ("statement between", 'IMP_LOG_ERROR("a");\n  ok_ = false;\n  return;\n', []),
        ("closing brace between", 'if (!w) {\n  IMP_LOG_WARN("a");\n}\nreturn;\n', []),
        ("designed fallback", 'IMP_FALLBACK_WARN(s_fb, "a %d", n);\n  return;\n', [1]),
        ("commented-out call", '// IMP_LOG_ERROR("a");\n  return;\n', []),
    ]
    for name, text, want_lines in texts:
        got_lines = find_lines(text)
        if got_lines == want_lines:
            ok += 1
        else:
            print(f"selftest FAIL: {name}: lines {got_lines}, wanted {want_lines}")
    total = len(cases) + len(rows) + len(texts)
    print(f"selftest: {ok}/{total} cases")
    return 0 if ok == total else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update", action="store_true")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    sites = scan()
    hits = {rel: len(lines) for rel, lines in sites.items()}
    if args.list:
        for rel in sorted(sites):
            for line in sites[rel]:
                print(f"{rel}:{line}")
        return 0
    allowed, reasons = read_allowlist()
    if args.update:
        write_allowlist(hits, reasons)
        print(f"allowlist updated: {len(hits)} files, {sum(hits.values())} exits")
        return 0
    print(f"log-and-return: {len(hits)} files / {sum(hits.values())} exits behind an ERROR or WARN line in "
          f"{', '.join(ROOTS)} (allowlist: {len(allowed)} files / {sum(allowed.values())})")
    fails = verdict(hits, allowed) + reason_fails(hits, reasons)
    for f in fails:
        print("  " + f)
    if fails:
        print("FAIL: an exit that leaves an output unwritten throws or returns a checked status "
              "(tools/silent_void_return_allowlist.txt, --list names the lines).")
        return 1
    print("OK: no new log-and-return exit.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
