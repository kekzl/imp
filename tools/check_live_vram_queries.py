#!/usr/bin/env python3
"""I4 gate: capacity is planned, not discovered.

docs/internals/MEMORY.md invariant I4: sizing decisions come from the plan, not from a
reading of free device memory taken while the engine builds itself. This gate counts the
readings (cudaMemGetInfo, vram_budget_mem_get_info, vram_budget_mem_get_info_ex) outside
the query layer (src/memory/vram_query.*) against tools/live_vram_query_allowlist.txt.

The list only shrinks: a file that reads more often than its budget fails, a file that is
not listed fails, and an entry for a file that no longer reads fails as stale.

Usage:
    python3 tools/check_live_vram_queries.py            # check (CI)
    python3 tools/check_live_vram_queries.py --update   # rewrite the allowlist
    python3 tools/check_live_vram_queries.py --selftest
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SRC = REPO / "src"
ALLOWLIST = REPO / "tools" / "live_vram_query_allowlist.txt"
EXEMPT = ("src/memory/vram_query.cpp", "src/memory/vram_query.h")
SUFFIXES = (".cpp", ".cu", ".h", ".cuh", ".hpp")
PATTERN = re.compile(r"\b(cudaMemGetInfo|vram_budget_mem_get_info_ex|vram_budget_mem_get_info)\s*\(")
COMMENT_LINE = re.compile(r"^\s*(//|\*|/\*)")


def count_text(text: str) -> int:
    n = 0
    for line in text.splitlines():
        if COMMENT_LINE.match(line):
            continue
        code = line.split("//", 1)[0]
        n += len(PATTERN.findall(code))
    return n


def scan() -> dict[str, int]:
    hits: dict[str, int] = {}
    for path in sorted(SRC.rglob("*")):
        if path.suffix not in SUFFIXES or not path.is_file():
            continue
        rel = path.relative_to(REPO).as_posix()
        if rel in EXEMPT:
            continue
        n = count_text(path.read_text(encoding="utf-8", errors="replace"))
        if n:
            hits[rel] = n
    return hits


def read_allowlist() -> dict[str, int]:
    out: dict[str, int] = {}
    if not ALLOWLIST.exists():
        return out
    for line in ALLOWLIST.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        path, _, rest = s.partition("#")
        out[path.strip()] = int(rest.strip())
    return out


def write_allowlist(hits: dict[str, int]) -> None:
    body = [
        "# I4 allowlist: files that read free device memory outside src/memory/vram_query.*.",
        "# Generated by tools/check_live_vram_queries.py --update. THIS LIST ONLY SHRINKS:",
        "# a new reading needs a plan input instead (docs/internals/MEMORY.md, invariant I4).",
        "#",
        f"# remaining: {len(hits)} files, {sum(hits.values())} readings",
        "",
    ]
    body += [f"{rel}  # {hits[rel]}" for rel in sorted(hits)]
    ALLOWLIST.write_text("\n".join(body) + "\n", encoding="utf-8")


def verdict(hits: dict[str, int], allowed: dict[str, int]) -> list[str]:
    fails = []
    for rel in sorted(hits):
        if rel not in allowed:
            fails.append(f"FAIL {rel}: {hits[rel]} reading(s) of free device memory, file not on the allowlist")
        elif hits[rel] > allowed[rel]:
            fails.append(f"FAIL {rel}: {hits[rel]} reading(s), budget {allowed[rel]}")
    for rel in sorted(allowed):
        if rel not in hits:
            fails.append(f"FAIL {rel}: listed but no longer reads; delete the entry (--update)")
        elif hits[rel] < allowed[rel]:
            fails.append(f"FAIL {rel}: {hits[rel]} reading(s), budget {allowed[rel]}: lower it (--update)")
    return fails


def selftest() -> int:
    cases = [
        ("a new file", {"a.cpp": 1}, {}, 1),
        ("over budget", {"a.cpp": 3}, {"a.cpp": 2}, 1),
        ("stale entry", {}, {"a.cpp": 2}, 1),
        ("under budget", {"a.cpp": 1}, {"a.cpp": 2}, 1),
        ("exact", {"a.cpp": 2, "b.cu": 1}, {"a.cpp": 2, "b.cu": 1}, 0),
    ]
    ok = 0
    for name, hits, allowed, want in cases:
        got = len(verdict(hits, allowed))
        if (got > 0) == (want > 0):
            ok += 1
        else:
            print(f"selftest FAIL: {name}: {got} failure(s), wanted {'some' if want else 'none'}")
    text = "// cudaMemGetInfo(&a, &b)\nint x = 0;  // vram_budget_mem_get_info(\ncudaMemGetInfo(&f, &t); vram_budget_mem_get_info_ex(&f, &t, true);\n"
    if count_text(text) == 2:
        ok += 1
    else:
        print(f"selftest FAIL: comment handling counted {count_text(text)}, wanted 2")
    print(f"selftest: {ok}/{len(cases) + 1} cases")
    return 0 if ok == len(cases) + 1 else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    hits = scan()
    if args.update:
        write_allowlist(hits)
        print(f"allowlist updated: {len(hits)} files, {sum(hits.values())} readings")
        return 0
    allowed = read_allowlist()
    print(f"I4: {len(hits)} files / {sum(hits.values())} readings of free device memory outside "
          f"src/memory/vram_query.* (allowlist: {len(allowed)} files / {sum(allowed.values())})")
    fails = verdict(hits, allowed)
    for f in fails:
        print("  " + f)
    if fails:
        print("FAIL: sizing reads the device instead of the plan (invariant I4).")
        return 1
    print("OK: no new reading of free device memory.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
