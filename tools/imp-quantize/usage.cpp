#include "usage.h"

#include <cstdio>

void usage() {
    printf(
        "usage: imp-quantize --model <safetensors-dir> --out <dir> [--calib <file>]\n"
        "                    [--format modelopt|vllm] [--lm-head [fp8|nvfp4|source]]\n"
        "                    [--kv-hint auto|fp8|none] [--dry-run]\n"
        "\n"
        "  --model DIR   source checkpoint (BF16/FP16 SafeTensors + config.json)\n"
        "  --out DIR     destination; created if missing\n"
        "  --format F    output layout (default modelopt):\n"
        "                  modelopt            .weight / .weight_scale_2, declared in\n"
        "                                      hf_quant_config.json. imp reads it.\n"
        "                  vllm                compressed-tensors nvfp4-pack-quantized:\n"
        "                  (= compressed-tensors)  .weight_packed / .weight_global_scale,\n"
        "                                      declared in config.json. imp AND vLLM read\n"
        "                                      it, and fused layers (q/k/v, gate/up) share\n"
        "                                      one tensor scale, which vLLM requires.\n"
        "  --calib FILE  activation calibration (AWQ scaling). Produce it with:\n"
        "                  imp-cli --model DIR --perplexity <corpus> --calibrate FILE\n"
        "                Without it the quantization is plain round-to-nearest,\n"
        "                which costs measurably more quality (see the header).\n"
        "  --gptq FILE   GPTQ against IMPHES01 second moments (imp-cli --perplexity <corpus>\n"
        "                --calibrate F --set calibration.hessian=true writes F.hess)\n"
        "  --gptq-damp X fraction of mean diag(H) added to its diagonal (default 10;\n"
        "                0.01 loses to round-to-nearest: Qwen3-1.7B 22.58 vs 19.63)\n"
        "  --gptaq FILE  GPTAQ against IMPHES02 pairs from the AWQ export built with the same\n"
        "                --calib (calibration.pair_dump on the source, pair_read on the export\n"
        "                writes F.gptaq); damp from --gptq-damp. F1,F2,... merges one file\n"
        "                per layer group (calibration.pair_layer_begin/end); weights\n"
        "                without an entry round to nearest\n"
        "  --gptaq-alpha A  scale of the asymmetric term (default 0.25; 0 = GPTQ on the\n"
        "                export's inputs)\n"
        "  --calib-weight abs|sq  error weight of the AWQ search (default abs;\n"
        "                sq loses at wide GQA: Qwen3-14B BD 9.9068 abs vs 10.0563 sq)\n"
        "  --calib-groups ABCDEG\n"
        "                Which AWQ scale groups run. Default by GQA width:\n"
        "                ABCDEG when n_rep < 5 or the model has GDN layers,\n"
        "                BDEG on dense models with n_rep >= 5.\n"
        "                  A q,k,v  <- input_layernorm        C o_proj   <- v_proj\n"
        "                  B gate,up<- post_attention_norm    D down_proj<- up_proj\n"
        "                  G linear_attn.in_proj_* <- input_layernorm   (qwen3_5 GDN)\n"
        "                  E linear_attn.out_proj  <- linear_attn.norm  (qwen3_5 GDN)\n"
        "                  X experts.*.gate,up <- pre_feedforward_layernorm_2 (Gemma-4)\n"
        "                  Y experts.E.down    <- experts.E.up (every MoE)\n"
        "                  K kv_b_proj <- kv_a_layernorm   Q q_b_proj <- q_a_layernorm (MLA)\n"
        "                  S shared_experts.down <- shared_experts.up (DeepSeek, GLM)\n"
        "                X, Y are opt-in, no measured gain: on Gemma-4-26B every set\n"
        "                lands inside the RTN rounding band (16.76..19.01 PPL);\n"
        "                gemma4 needs an explicit selector.\n"
        "                E and G exist only on the GDN hybrids and are NOT measured\n"
        "                against an uncalibrated twin yet.\n"
        "                The ATTENTION groups (A, C) are what breaks on wide GQA:\n"
        "                Qwen3-14B (n_rep=5) ABCD 12.2634, BD 9.9068, round-to-\n"
        "                nearest 9.9849 PPL. Pass a subset to attribute a bad\n"
        "                result. See docs/QUANTIZATION.md.\n"
        "  --lm-head [fp8|nvfp4|source]\n"
        "                how lm_head is written. fp8 (default for modelopt): per-row\n"
        "                E4M3 + F32 row scales, the head imp's gemm.nvfp4_lm_head=auto\n"
        "                builds at load, served without conversion (half the BF16\n"
        "                bytes). nvfp4 (bare flag): quantized like any Linear.\n"
        "                source (default for vllm): copied as is. A tied head has\n"
        "                no lm_head tensor and is unaffected.\n"
        "  --kv-hint auto|fp8|none\n"
        "                kv_cache_quant_algo in hf_quant_config.json (modelopt only).\n"
        "                auto (default): FP8 for model_type qwen3 / qwen3_moe, the\n"
        "                families with a measured FP8 KV PPL, else null.\n"
        "  --keep-attn-gate\n"
        "                keep a fused Q+gate q_proj (Qwen3.5 / Qwen3-Next\n"
        "                `attn_output_gate`) out of NVFP4. OFF by default: the gate\n"
        "                half carries #1273's divergence, but excluding it measured\n"
        "                ~1.5%% WORSE on perplexity, not better, and costs 1-4%% of\n"
        "                the checkpoint. Kept for models with a higher gate share.\n"
        "  --keep-gdn-proj [all|in,gate,out]\n"
        "                keep GDN linear_attn projections at source precision: in =\n"
        "                in_proj_qkv(+a/b), gate = in_proj_z, out = out_proj; bare flag\n"
        "                = all, the Qwen3.6-35B-A3B-NVFP4 recipe. The runtime runs them\n"
        "                through its F16 GDN path (FP8 decode sidecar, opt-in NVFP4\n"
        "                prefill copies). Qwen3.8-27B: all = 10.6 GiB BF16 and the\n"
        "                checkpoint no longer fits 32 GB; in = 5 GiB fits.\n"
        "  --gdn-proj-mxfp8\n"
        "                write the kept GDN projections as MXFP8 (E4M3 + E8M0 scale\n"
        "                per 32, `<m>.weight_scale` U8 [N,K/32]): half the BF16 bytes.\n"
        "                The loader widens them to BF16. Implies --keep-gdn-proj all\n"
        "                unless that flag names roles.\n"
        "  --fp8-keep L.G[,...]\n"
        "                write these dense projections as FP8 E4M3 with one F32\n"
        "                per-tensor scale instead of NVFP4; G = qkv | o | gate_up |\n"
        "                down, L = layer or * (\"*.down,27.gate_up\"). Declared as\n"
        "                Modelopt MIXED_PRECISION; modelopt format only.\n"
        "  --fp8-budget P\n"
        "                keep the highest-scoring units in FP8 while the export\n"
        "                stays within P %% over the pure NVFP4 export; needs\n"
        "  --fp8-score F  F.hess (calibration.hessian): score = output loss\n"
        "                sum(dW H dW^T) of NVFP4 minus FP8; else a text file of\n"
        "                '<layer>.<group> <score>' lines (e.g. measured PPL gains)\n"
        "  --dry-run    report what would be quantized and how large the result\n"
        "                will be, against what the card has left. Writes nothing.\n");
}
