#!/usr/bin/env python3
"""I5 gate: one move-only owner per device allocation.

docs/internals/MEMORY.md invariant I5: a device allocation is released by the owner type
that holds it, through the allocator that produced it. This gate counts what still does it
by hand outside src/memory/, against tools/owning_free_allowlist.txt:

  [release sites]         calls of the free functions (device_free_all*, vram_free,
                          weights_free, device_free_async_checked) and `<allocator>.free(`
                          on the usual allocator names (vram_alloc_, alloc_, alloc, va_, va)
  [owner-or-view flags]   `bool ...owned...` declarations: a pointer whose owner is decided
                          at run time

The body of the vram_free helper itself (src/exec/executor_helpers.h) is not a site.

The list only shrinks: a file over its count fails, a file that is not listed fails, and an
entry for a file that no longer has a site fails as stale.

Usage:
    python3 tools/check_owning_frees.py            # check (CI)
    python3 tools/check_owning_frees.py --update   # rewrite the allowlist
    python3 tools/check_owning_frees.py --selftest
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SRC = REPO / "src"
ALLOWLIST = REPO / "tools" / "owning_free_allowlist.txt"
EXEMPT_DIR = "src/memory/"
HELPER_FILE = "src/exec/executor_helpers.h"
SUFFIXES = (".cpp", ".cu", ".h", ".cuh", ".hpp")
FREE_FN = re.compile(
    r"\b(device_free_all|device_free_all_async|device_free_all_n|device_free_all_async_n|"
    r"device_free_async_checked|vram_free|weights_free)\s*\("
)
FREE_METHOD = re.compile(r"\b(vram_alloc_|alloc_|alloc|va_|va)\s*(\.|->)\s*free\s*\(")
OWNED_FLAG = re.compile(r"\bbool\s+\w*owned\w*\b")
COMMENT_LINE = re.compile(r"^\s*(//|\*|/\*)")
HELPER_HEAD = re.compile(r"^static inline void vram_free\s*\(")
SITES = "release sites"
FLAGS = "owner-or-view flags"
SECTIONS = (SITES, FLAGS)

Counts = dict[str, dict[str, int]]


def code_lines(text: str) -> list[str]:
    out = []
    for line in text.splitlines():
        if COMMENT_LINE.match(line):
            continue
        out.append(line.split("//", 1)[0])
    return out


def drop_helper_body(text: str) -> str:
    """Removes the definition of vram_free: from its head to the closing brace in column 0."""
    out, inside = [], False
    for line in text.splitlines():
        if not inside and HELPER_HEAD.match(line):
            inside = True
        if not inside:
            out.append(line)
        elif line.startswith("}"):
            inside = False
    return "\n".join(out)


def count_sites(text: str) -> int:
    return sum(len(FREE_FN.findall(c)) + len(FREE_METHOD.findall(c)) for c in code_lines(text))


def count_flags(text: str) -> int:
    return sum(len(OWNED_FLAG.findall(c)) for c in code_lines(text))


def scan() -> Counts:
    hits: Counts = {s: {} for s in SECTIONS}
    for path in sorted(SRC.rglob("*")):
        if path.suffix not in SUFFIXES or not path.is_file():
            continue
        rel = path.relative_to(REPO).as_posix()
        if rel.startswith(EXEMPT_DIR):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if rel == HELPER_FILE:
            text = drop_helper_body(text)
        for section, n in ((SITES, count_sites(text)), (FLAGS, count_flags(text))):
            if n:
                hits[section][rel] = n
    return hits


def parse_allowlist(text: str) -> Counts:
    out: Counts = {s: {} for s in SECTIONS}
    section = SITES
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        if s.startswith("[") and s.endswith("]"):
            section = s[1:-1]
            out.setdefault(section, {})
            continue
        path, _, rest = s.partition("#")
        out[section][path.strip()] = int(rest.strip())
    return out


def read_allowlist() -> Counts:
    if not ALLOWLIST.exists():
        return {s: {} for s in SECTIONS}
    return parse_allowlist(ALLOWLIST.read_text(encoding="utf-8"))


def render_allowlist(hits: Counts) -> str:
    sites, flags = hits[SITES], hits[FLAGS]
    body = [
        "# I5 allowlist: files outside src/memory/ that release device memory by hand, and",
        "# the `bool ...owned...` flags that decide an owner at run time.",
        "# Generated by tools/check_owning_frees.py --update. THIS LIST ONLY SHRINKS:",
        "# a new allocation gets a move-only owner instead (VramOwned, src/memory/vram_owned.h;",
        "# docs/internals/MEMORY.md, invariant I5).",
        "#",
        f"# remaining: {sum(sites.values())} release sites in {len(sites)} files, "
        f"{sum(flags.values())} owner-or-view flags in {len(flags)} files",
    ]
    for section in SECTIONS:
        body += ["", f"[{section}]"]
        body += [f"{rel}  # {hits[section][rel]}" for rel in sorted(hits[section])]
    return "\n".join(body) + "\n"


def verdict(hits: dict[str, int], allowed: dict[str, int], what: str) -> list[str]:
    fails = []
    for rel in sorted(hits):
        if rel not in allowed:
            fails.append(f"FAIL {rel}: {hits[rel]} {what}, file not on the allowlist")
        elif hits[rel] > allowed[rel]:
            fails.append(f"FAIL {rel}: {hits[rel]} {what}, budget {allowed[rel]}")
    for rel in sorted(allowed):
        if rel not in hits:
            fails.append(f"FAIL {rel}: listed but has no {what} left; delete the entry (--update)")
        elif hits[rel] < allowed[rel]:
            fails.append(f"FAIL {rel}: {hits[rel]} {what}, budget {allowed[rel]}: lower it (--update)")
    return fails


def verdict_all(hits: Counts, allowed: Counts) -> list[str]:
    fails = []
    for section in SECTIONS:
        fails += verdict(hits.get(section, {}), allowed.get(section, {}), section)
    for section in allowed:
        if section not in SECTIONS:
            fails.append(f"FAIL [{section}]: unknown allowlist section")
    return fails


def selftest() -> int:
    cases = [
        ("a new file", {"a.cpp": 1}, {}, 1),
        ("over budget", {"a.cpp": 3}, {"a.cpp": 2}, 1),
        ("stale entry", {}, {"a.cpp": 2}, 1),
        ("under budget", {"a.cpp": 1}, {"a.cpp": 2}, 1),
        ("exact", {"a.cpp": 2, "b.cu": 1}, {"a.cpp": 2, "b.cu": 1}, 0),
    ]
    total = ok = 0

    def check(name: str, cond: bool, detail: str = "") -> None:
        nonlocal total, ok
        total += 1
        if cond:
            ok += 1
        else:
            print(f"selftest FAIL: {name}{': ' + detail if detail else ''}")

    for name, hits, allowed, want in cases:
        got = len(verdict(hits, allowed, SITES))
        check(name, (got > 0) == (want > 0), f"{got} failure(s)")

    text = (
        "// device_free_all(p);\n"
        " * vram_alloc_.free(p);\n"
        "int x = 0;  // weights_free(p)\n"
        "device_free_all(a, b); vram_free(alloc, p);\n"
        "vram_alloc_.free(p); alloc->free(q); va_ . free(r);\n"
        "device_free_all_async(s, p); device_free_async_checked(p, s); weights_free(p);\n"
        "std::free(p); pool.free(p); my_alloc.free(p); vfree(p);\n"
    )
    check("comment lines are not counted", count_sites(text) == 8, f"counted {count_sites(text)}, wanted 8")

    flags = "// bool owned = false;\nbool owned = false; bool ptr_owned_ = true;\nbool own = false; bool disowned;\n"
    check("owner-or-view flags", count_flags(flags) == 3, f"counted {count_flags(flags)}, wanted 3")

    helper = (
        "static inline void vram_free(VRAMAllocator* alloc, void* ptr) {\n"
        "    if (alloc)\n        alloc->free(ptr);\n    else\n        device_free_all(ptr);\n}\n"
        "inline void f(void* p) { device_free_all(p); }\n"
    )
    n = count_sites(drop_helper_body(helper))
    check("the helper body is not a site", n == 1, f"counted {n}, wanted 1")

    allow = parse_allowlist(render_allowlist({SITES: {"a.cpp": 2}, FLAGS: {"b.h": 1}}))
    check("allowlist round trip", allow == {SITES: {"a.cpp": 2}, FLAGS: {"b.h": 1}}, str(allow))
    check("a flag in a file listed only for sites fails",
          len(verdict_all({SITES: {"a.cpp": 2}, FLAGS: {"a.cpp": 1}}, {SITES: {"a.cpp": 2}, FLAGS: {}})) == 1)
    check("both sections exact pass",
          not verdict_all({SITES: {"a.cpp": 2}, FLAGS: {"b.h": 1}}, {SITES: {"a.cpp": 2}, FLAGS: {"b.h": 1}}))

    print(f"selftest: {ok}/{total} cases")
    return 0 if ok == total else 1


def totals(c: Counts) -> str:
    s, f = c.get(SITES, {}), c.get(FLAGS, {})
    return f"{sum(s.values())} release sites in {len(s)} files, {sum(f.values())} owner-or-view flags in {len(f)} files"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    hits = scan()
    if args.update:
        ALLOWLIST.write_text(render_allowlist(hits), encoding="utf-8")
        print(f"allowlist updated: {totals(hits)}")
        return 0
    allowed = read_allowlist()
    print(f"I5: {totals(hits)} outside src/memory/ (allowlist: {totals(allowed)})")
    fails = verdict_all(hits, allowed)
    for f in fails:
        print("  " + f)
    if fails:
        print("FAIL: device memory released by hand instead of by a move-only owner (invariant I5).")
        return 1
    print("OK: no new hand-written release site, no new owner-or-view flag.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
